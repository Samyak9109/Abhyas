// FR-033, NFR-012, ADR-019: Static HTML prerendering script for public pages.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webDir = path.resolve(__dirname, "..");
const distDir = path.resolve(webDir, "dist");

async function main() {
  console.log("Starting static HTML prerendering (ADR-019, NFR-012)...");

  // Verify dist exists
  try {
    await fs.access(distDir);
  } catch {
    console.error("dist/ not found. Run 'vite build' before prerendering.");
    process.exit(1);
  }

  // Read base template generated by vite build
  const templatePath = path.resolve(distDir, "index.html");
  const templateHtml = await fs.readFile(templatePath, "utf-8");

  // Save a copy as dist/app/index.html for client-side /app/* routes
  const appDir = path.resolve(distDir, "app");
  await fs.mkdir(appDir, { recursive: true });
  await fs.writeFile(path.resolve(appDir, "index.html"), templateHtml, "utf-8");

  // Extract head links (CSS, scripts) from template
  const cssMatches = templateHtml.match(/<link rel="stylesheet"[^>]*>/g) || [];
  const scriptMatches = templateHtml.match(/<script type="module"[^>]*><\/script>/g) || [];

  const headAssets = cssMatches.join("\n    ");
  const bodyScripts = scriptMatches.join("\n    ");

  // Initialize Vite SSR loader
  const vite = await createServer({
    root: webDir,
    server: { middlewareMode: true },
    appType: "custom",
    optimizeDeps: { noDiscovery: true },
  });

  try {
    const { renderPage, PUBLIC_ROUTES } = await vite.ssrLoadModule(
      "/src/screens/public/prerender.tsx"
    );

    for (const route of PUBLIC_ROUTES) {
      const page = renderPage(route);
      const url = `https://abhyas.app${route === "/" ? "" : route}`;

      const fullHtml = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta
      http-equiv="Content-Security-Policy"
      content="default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; font-src 'self'; img-src 'self' data:; worker-src 'self' blob:; manifest-src 'self'; connect-src 'self' https://generativelanguage.googleapis.com https://api.openai.com http://localhost:* http://127.0.0.1:*; object-src 'none'; base-uri 'self';"
    />
    <title>${page.title}</title>
    <meta name="description" content="${page.description}" />
    <link rel="manifest" href="/manifest.webmanifest" />
    <link rel="icon" type="image/svg+xml" href="/icon.svg" />
    <meta name="theme-color" content="#121110" />
    <!-- Open Graph / Social Sharing -->
    <meta property="og:type" content="website" />
    <meta property="og:url" content="${url}" />
    <meta property="og:title" content="${page.title}" />
    <meta property="og:description" content="${page.description}" />
    <meta property="og:site_name" content="Abhyas" />
    <!-- Twitter Card -->
    <meta name="twitter:card" content="summary" />
    <meta name="twitter:title" content="${page.title}" />
    <meta name="twitter:description" content="${page.description}" />
    <!-- Preloaded self-hosted fonts above the fold (ADR-020, NFR-025) -->
    <link rel="preload" href="/fonts/pixelify-sans-700.woff2" as="font" type="font/woff2" crossorigin="anonymous" />
    <link rel="preload" href="/fonts/instrument-sans-400.woff2" as="font" type="font/woff2" crossorigin="anonymous" />
    ${headAssets}
    <script src="/theme-init.js"></script>
  </head>
  <body>
    <div id="root">${page.html}</div>
    ${bodyScripts}
  </body>
</html>`;

      if (route === "/") {
        await fs.writeFile(path.resolve(distDir, "index.html"), fullHtml, "utf-8");
        console.log("  Prerendered: / -> dist/index.html");
      } else if (route === "/404") {
        await fs.writeFile(path.resolve(distDir, "404.html"), fullHtml, "utf-8");
        console.log("  Prerendered: /404 -> dist/404.html");
      } else {
        const routeSubdir = path.resolve(distDir, route.replace(/^\//, ""));
        await fs.mkdir(routeSubdir, { recursive: true });
        await fs.writeFile(path.resolve(routeSubdir, "index.html"), fullHtml, "utf-8");
        console.log(`  Prerendered: ${route} -> dist${route}/index.html`);
      }
    }

    // Generate sitemap.xml (NFR-012)
    const sitemapContent = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>https://abhyas.app/</loc>
    <changefreq>weekly</changefreq>
    <priority>1.0</priority>
  </url>
  <url>
    <loc>https://abhyas.app/privacy</loc>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
  </url>
  <url>
    <loc>https://abhyas.app/open-source</loc>
    <changefreq>monthly</changefreq>
    <priority>0.7</priority>
  </url>
  <url>
    <loc>https://abhyas.app/guide/keys</loc>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
  </url>
  <url>
    <loc>https://abhyas.app/help</loc>
    <changefreq>monthly</changefreq>
    <priority>0.7</priority>
  </url>
</urlset>
`;
    await fs.writeFile(path.resolve(distDir, "sitemap.xml"), sitemapContent, "utf-8");
    console.log("  Generated: dist/sitemap.xml");

    // Generate robots.txt
    const robotsContent = `User-agent: *
Allow: /
Disallow: /app/

Sitemap: https://abhyas.app/sitemap.xml
`;
    await fs.writeFile(path.resolve(distDir, "robots.txt"), robotsContent, "utf-8");
    console.log("  Generated: dist/robots.txt");

    console.log("Prerendering completed successfully.");
  } finally {
    await vite.close();
  }
}

main().catch((err) => {
  console.error("Prerendering failed:", err);
  process.exit(1);
});
